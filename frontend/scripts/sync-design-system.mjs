/**
 * Copies the Jura Solutions design system into the repo.
 *
 * The design system is authoritative and lives outside this repo at
 * `jurasolutions/design-system/`. This repo has to run standalone, so a copy
 * is vendored into `src/design-system/`.
 *
 * The copy is read-only: never hand-edit it. Change the design system at
 * source, then run `npm run sync:ds` to bring the change across.
 *
 * One substitution is made on the copy, and only on the copy. The design
 * system's `tokens/fonts.css` pulls Outfit, DM Sans and IBM Plex Mono from
 * Google Fonts over the network. This app renders documents offline and in
 * headless Chromium, where that request silently fails and the document comes
 * out in Helvetica — the wrong typeface on a document a client keeps for five
 * years. The vendored `tokens/fonts.css` is rewritten to point at
 * `src/styles/fonts.local.css`, which serves the same three families from the
 * local Fontsource packages. The design system at source is untouched.
 */
import { cp, rm, stat, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(here, "..");
const source = process.env.JURA_DS_PATH
  ? resolve(process.env.JURA_DS_PATH)
  : resolve(frontendRoot, "../../../design-system");
const target = resolve(frontendRoot, "src/design-system");

// Only what the app needs at build time. The preview cards, the generated
// bundle and the docs stay at source.
const INCLUDE = ["styles.css", "tokens", "assets", "components"];
const SKIP = /\.(card\.html|prompt\.md)$/;

const LOCAL_FONTS_CSS = `/* Generated by scripts/sync-design-system.mjs — do not edit.
 *
 * Replaces the design system's remote Google Fonts @import with the local
 * Fontsource packages. Same three families, same weights, no network.
 * See the comment at the top of scripts/sync-design-system.mjs for why.
 */
@import url("../../styles/fonts.local.css");
`;

try {
  await stat(source);
} catch {
  console.error(`Design system not found at ${source}`);
  console.error("Set JURA_DS_PATH to point at jurasolutions/design-system.");
  process.exit(1);
}

await rm(target, { recursive: true, force: true });

for (const entry of INCLUDE) {
  await cp(resolve(source, entry), resolve(target, entry), {
    recursive: true,
    filter: (src) => !SKIP.test(src),
  });
}

await mkdir(resolve(target, "tokens"), { recursive: true });
await writeFile(resolve(target, "tokens/fonts.css"), LOCAL_FONTS_CSS, "utf8");

console.log(`Design system synced from ${source} to src/design-system`);
console.log("tokens/fonts.css rewritten to load fonts locally (no network).");
